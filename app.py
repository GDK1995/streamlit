if prompt := st.chat_input("Напишите боту..."):
    with st.chat_message("user"):
        st.markdown(prompt)
    st.session_state.messages.append({"role": "user", "content": prompt})

    # Пересобираем всю историю сообщений для отправки в API через types.Content
    # Это железобетонно обходит баг v1beta с автоматическим навешиванием 'models/'
    formatted_contents = []
    for msg in st.session_state.messages:
        api_role = "model" if msg["role"] == "assistant" else "user"
        formatted_contents.append(
            types.Content(
                role=api_role,
                parts=[types.Part.from_text(text=msg["content"])]
            )
        )

    # Запрос к API Google Gemini
    try:
        config = types.GenerateContentConfig(
            system_instruction=SYSTEM_INSTRUCTION,
            temperature=0.7,
        )
        
        response = st.session_state.client.models.generate_content(
            model=MODEL_NAME,
            contents=formatted_contents,
            config=config
        )
        
        # Выводим ответ и сохраняем его в историю
        with st.chat_message("assistant"):
            st.markdown(response.text)
        st.session_state.messages.append({"role": "assistant", "content": response.text})
        
    except Exception as e:
        with st.chat_message("assistant"):
            st.error(f"Произошла ошибка API: {e}")